"""Split attributed collections without reconstructing or rewriting user edits."""
from __future__ import annotations

import json
import shutil
import hashlib
import uuid
from pathlib import Path
from collections import defaultdict
from PySide6.QtCore import QLockFile

from gallery.library import Library
from gallery.updates import baseline, fingerprint
from gallery.sources import normalize_source, SUPPORTED


def recover_split(root):
    root = Path(root).resolve()
    transaction = root.parent / ("." + root.name + ".gallery-split")
    marker = transaction / "transaction.json"
    if not marker.exists():
        return
    data = json.loads(marker.read_text("utf-8"))
    if data.get("root") != str(root):
        raise ValueError("拆库恢复路径无效")
    backup = transaction / "original-backup"
    completed = transaction / "completed.json"
    if completed.exists() and (root / "gallery.sqlite3").exists() and all(
            Path(name).name == name and (root.parent / name / "gallery.sqlite3").exists() for name in data["outputs"]):
        marker.unlink()
        return
    if backup.exists():
        if root.exists():
            root.rename(transaction / "interrupted-local")
        backup.rename(root)
    for name in data["outputs"]:
        # Only direct names generated by the application may be moved back.
        if Path(name).name != name:
            raise ValueError("拆库恢复目标无效")
        target = root.parent / name
        if target.exists():
            target.rename(transaction / ("interrupted-" + name))
    marker.unlink()
    completed.unlink(missing_ok=True)


def split_library(root):
    root = Path(root).resolve()
    transaction = root.parent / ("." + root.name + ".gallery-split")
    groups = defaultdict(set)
    all_records = baseline(root)
    from gallery.catalog import Catalog
    manifests = Catalog.manifests(root)
    for record in all_records:
        if record["source"]:
            source = normalize_source(record["source"])
            groups[source].add(record["picture"])
    if not groups:
        raise ValueError("未发现可确认的来源映射")
    targets = [(source, root.parent / SUPPORTED[source.removeprefix("https://github.com/")]) for source in groups]
    if any(path.exists() or path == root for _, path in targets):
        raise ValueError("拆分目标库已存在，请先处理重名，程序不会覆盖")
    maintenance = QLockFile(str(root.parent / ("." + root.name + ".maintenance.lock")))
    lock = QLockFile(str(root / ".gallery.lock"))
    maintenance.setStaleLockTime(0)
    lock.setStaleLockTime(0)
    if not maintenance.tryLock(0):
        raise ValueError("素材库正在维护")
    if not lock.tryLock(0):
        maintenance.unlock()
        raise ValueError("请先关闭该库的其他程序和详情窗口再拆分")
    try:
        if transaction.exists():
            if (transaction / "original-backup").exists() or (transaction / "transaction.json").exists():
                raise ValueError("已存在拆库备份或恢复记录，请先重启检查，避免重复迁移")
            transaction.rename(transaction.with_name(transaction.name + ".failed-" + uuid.uuid4().hex))
        before = fingerprint(root)
        transaction.mkdir()
        original_pictures = {}
        with Library(root) as library:
            ids = {p.id for p in library.images()}
            for pid in ids:
                original_pictures[pid] = (library.picture(pid), hashlib.sha256(library.original(pid).read_bytes()).hexdigest())
        known = set().union(*groups.values()) & ids
        stages = []
        for source, target in targets:
            stage = transaction / target.name
            shutil.copytree(root, stage, ignore=shutil.ignore_patterns(".gallery.lock"))
            keep = groups[source] & ids
            with Library(stage) as library:
                library.delete_images(sorted(ids - keep))
                library.validate()
                for pid in keep:
                    saved, digest = original_pictures[pid]
                    if library.picture(pid) != saved or hashlib.sha256(library.original(pid).read_bytes()).hexdigest() != digest:
                        raise ValueError("拆分预演未能保留原记录或图片")
            for file in stage.glob("*来源*json"):
                data = json.loads(file.read_text("utf-8"))
                if normalize_source(data.get("repository", data.get("source", ""))) != source:
                    file.unlink()
            for name, data in manifests:
                if normalize_source(data.get("repository", data.get("source", ""))) == source:
                    destination = stage / name
                    if destination.resolve().parent != stage.resolve():
                        raise ValueError("来源清单路径不能越出暂存目录")
                    destination.write_text(json.dumps(data, ensure_ascii=False), "utf-8")
            with Library(stage) as library:
                library.db.execute("DROP TABLE IF EXISTS source_manifests")
            (stage / "library-source.json").write_text(json.dumps({"source": source}), "utf-8")
            stages.append((source, target, stage))
        local = transaction / "local"
        shutil.copytree(root, local, ignore=shutil.ignore_patterns(".gallery.lock"))
        with Library(local) as library:
            library.delete_images(sorted(known))
            library.validate()
            if {p.id for p in library.images()} != ids - known:
                raise ValueError("拆分预演图片数量不守恒")
        for file in local.glob("*来源*json"):
            file.unlink()
        with Library(local) as library:
            library.db.execute("DROP TABLE IF EXISTS source_manifests")
            library.db.execute("DROP TABLE IF EXISTS source_images")
        if fingerprint(root) != before:
            raise ValueError("拆分期间素材库已变动，未提交")
        marker = transaction / "transaction.json"
        marker.write_text(json.dumps({"root": str(root), "outputs": [p.name for _, p in targets]}), "utf-8")
        lock.unlock()
        try:
            root.rename(transaction / "original-backup")
            for _, target, stage in stages:
                stage.rename(target)
            local.rename(root)
        except BaseException:
            recover_split(root)
            raise
        (transaction / "completed.json").write_text(json.dumps({"root": str(root),
            "outputs": [{"source": source, "name": target.name} for source, target in targets]}), "utf-8")
        marker.unlink()
        return targets
    finally:
        lock.unlock()
        maintenance.unlock()
